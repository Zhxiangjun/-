def base_effort(name: str, desc: str) -> int:
    text = name + desc
    for kw, d in EFFORT_RULES:
        if kw in text:
            return d
    return EFFORT_DEFAULT


def build():
    """返回功能字典列表（已完成工时与依赖推导）。"""
    prio_stage = {"P0": "MVP", "P1": "V1", "P2": "V2", "P3": "V3"}
    rows = []
    for mod, group, name, desc, prio, stage in FUNCS:
        d = base_effort(name, desc)
        eff = round(d * PHASE_FACTOR[stage])
        rows.append({
            "mod": mod, "group": group, "name": name, "desc": desc,
            "prio": prio, "stage": stage, "base": d, "effort": eff,
            # 阶段与优先级一致性校验（P0 应落在 MVP）
            "aligned": (prio_stage[prio] == stage),
        })
    return rows


MODULE_NAME = {m[0]: m[1] for m in MODULES}


def stage_summary(rows):
    out = {}
    for r in rows:
        s = out.setdefault(r["stage"], {"count": 0, "effort": 0, "P0": 0, "P1": 0, "P2": 0, "P3": 0})
        s["count"] += 1
        s["effort"] += r["effort"]
        s[r["prio"]] += 1
    return out


def module_summary(rows):
    out = {}
    for r in rows:
        s = out.setdefault(r["mod"], {"count": 0, "effort": 0, "stages": {}})
        s["count"] += 1
        s["effort"] += r["effort"]
        s["stages"][r["stage"]] = s["stages"].get(r["stage"], 0) + 1
    return out


